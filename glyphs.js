export function normaliseCharacter(character) {
  const source = String(character ?? " ");
  if (source === "ß") return "S";
  const stripped = source.normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  return stripped.toUpperCase().slice(0, 1) || " ";
}

